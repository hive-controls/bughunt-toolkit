"""Fast mode: synthesize a scoped, verified mission policy from a scan's own target set.

``bughunt scan <target> --fast --authorized`` removes the manual ``bughunt policy import`` step
for an authorized engagement. It puts the scan's targets in scope and writes a workspace policy
that authorizes EXACTLY the origins this scan will probe -- never a wildcard -- so the egress
safety gate passes for those origins while every other origin stays blocked. The gate itself is
untouched: "fast" removes the manual policy authoring, not the preflight.
"""

from __future__ import annotations

from datetime import datetime, timezone
import json
from pathlib import Path
import sys

from bughunt.core import workspace
from bughunt.core.policy import OPERATIONS, PolicyError, target_parts

FAST_MARKER = "bughunt-fast-mode"
_STALE_AFTER_SECONDS = 86400
_PERMITTED_OPERATIONS = ("passive", "active_scan")
_DEFAULT_USER_AGENT = "Bughunt-fast (+authorized surface mapping)"


class FastModeError(ValueError):
    """Fast-mode setup refused; no outbound action and no policy write may follow."""


def setup_scope(args) -> None:
    """Affirm authorization and guard against clobber, then put the targets in scope.

    Call before planning so the scan's out-of-scope rejection passes for the fast target(s).
    """
    if not getattr(args, "authorized", False):
        raise FastModeError(
            "fast mode requires --authorized to affirm you are authorized to test the "
            "target(s); nothing was written."
        )
    _guard_existing_policy()
    if any(getattr(args, flag, False) for flag in ("dns", "ct", "intel")):
        print(
            "WARNING: fast mode does not authorize DNS or CT enrichment; "
            "import a policy with explicit DNS and service-origin grants for those features. "
            "Other --intel analysis can still run.",
            file=sys.stderr,
        )
    workspace.init_workspace()
    tokens = _scope_tokens(args)
    if tokens:
        workspace.add_entries(tokens)


def synthesize_policy(urls: list[str], args) -> None:
    """Write a verified policy authorizing exactly the origins in ``urls``. Call after planning."""
    from bughunt.modules.policy import install_document

    install_document(build_document(urls, args))


def build_document(urls: list[str], args) -> dict:
    """The scoped, verified policy document mirroring the scan's exact origin set."""
    origins = _unique_origins(urls)
    if not origins:
        raise FastModeError("fast mode found no target origin to authorize.")
    methods = sorted({"GET", str(getattr(args, "method", "GET") or "GET").upper()})
    concurrency = max(1, int(getattr(args, "concurrency", 1) or 1))
    now = datetime.now(timezone.utc).isoformat()
    assets = [
        {
            "id": f"{FAST_MARKER}-{index}",
            "origin": origin,
            "paths": ["/"],
            "operations": list(_PERMITTED_OPERATIONS),
            "methods": methods,
        }
        for index, origin in enumerate(origins)
    ]
    return {
        "schema_version": 1,
        "mission": "fast-mode",
        "policy_version": "fast-1",
        "state": "verified",
        "source": f"{FAST_MARKER}: operator affirmed --authorized at {now}",
        "verified_at": now,
        "stale_after_seconds": _STALE_AFTER_SECONDS,
        "assets": assets,
        "exclusions": [],
        "permissions": {
            operation: operation in _PERMITTED_OPERATIONS for operation in OPERATIONS
        },
        "limits": {
            "requests_per_second": float(concurrency),
            "concurrency": concurrency,
        },
        "required_headers": {},
        "user_agent": _user_agent(args),
        "callback_domains": [],
        "ai_notes": "",
        "confidentiality_notes": "",
    }


def _policy_path() -> Path:
    return workspace.workspace_dir() / "policy.json"


def _guard_existing_policy() -> None:
    path = _policy_path()
    if not path.exists() or _is_fast_generated(path):
        return
    raise FastModeError(
        "workspace policy.json already exists and was not generated by fast mode; refusing to "
        "overwrite it. Remove it or run `bughunt policy import` to replace it deliberately."
    )


def _is_fast_generated(path: Path) -> bool:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, ValueError):
        return False
    return isinstance(data, dict) and str(data.get("source", "")).startswith(
        FAST_MARKER
    )


def _scope_tokens(args) -> list[str]:
    tokens = [
        token for token in (getattr(args, "targets", None) or []) if token.strip()
    ]
    targets_file = getattr(args, "targets_file", None)
    if targets_file:
        text = (
            Path(targets_file)
            .expanduser()
            .read_text(encoding="utf-8", errors="replace")
        )
        tokens.extend(workspace.live_lines(text))
    return tokens


def _unique_origins(urls: list[str]) -> list[str]:
    origins: list[str] = []
    for url in urls:
        try:
            origin, _path = target_parts(url)
        except PolicyError as exc:
            raise FastModeError(f"fast mode cannot authorize {url!r}: {exc}") from exc
        if origin not in origins:
            origins.append(origin)
    return origins


def _user_agent(args) -> str:
    agent = str(getattr(args, "user_agent", "") or "").strip()
    return agent or _DEFAULT_USER_AGENT
